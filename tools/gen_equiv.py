#!/usr/bin/env python3
"""Generate C for functions that have none, and keep what behaves like the original.

    gen_equiv.py LIST [--jobs N] [--limit N] [--image IMAGE]

LIST is a CSV with `image` and `address` columns (e.g. native_port/docs/exhibition_functions.csv);
every listed function without C (no exact source in src/, no draft in config/nonmatching.json) is:

  1. disassembled for m2c (tools/match.py m2c_asm: EE register names, jump tables visible), with
     $gp-relative and %hi/%lo data references turned into func_/D_ symbols;
  2. translated by m2c (tools/ext/m2c, target mipsee-gcc-c); an incomplete translation (leftover
     M2C_ macros other than M2C_FIELD/M2C_UNK, unset or saved registers, TODO/unhandled) is rejected;
  3. made compilable as the earlier draft generator did (absolute data as char arrays, names from
     config/symbol_addrs.txt) and compiled with ee-gcc-2.9, or mwcc-3.0.1b210 if that fails;
  4. judged by tools/equiv.py against the original.

The result of every function goes to build/gen/<image>.jsonl, the C of every function to
build/gen/<image>/func_ADDR.c. Only the verdict decides: a translation that compiles to different
instructions but behaves the same (EQUIVALENT) is kept, which the similarity-based draft admission
discarded. Admitting kept files into nonmatching/ is a separate step (--admit).

    gen_equiv.py --admit [--image IMAGE]

copies every EQUIVALENT generated file into nonmatching/<image>/, verifies it with
tools/nonmatching.py's checks and records it in config/nonmatching.json and the equivalence results
(docs/equivalent.md after `tools/equiv.py --report`).
"""
import csv
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
os.chdir(ROOT)

GP = 0x003EF370
OUT = os.path.join(ROOT, "build", "gen")
M2C = os.path.join(ROOT, "tools", "ext", "m2c", "m2c.py")
INCOMPLETE = re.compile(r"M2C_(?!FIELD\b|UNK(?:8|16|32|64)?\b|BITWISE\b)|saved_reg_|unset register|unhandled|Error|TODO", re.I)
HEADER = ("/* compiler: {comp} */\n"
          "/* Generated by tools/gen_equiv.py from m2c and kept because tools/equiv.py found it "
          "equivalent on generated cases; types and call contracts remain provisional. */\n"
          "#include \"pes6/m2c.h\"\n\n")


# ---- data references as symbols (from the earlier draft generator) -----------------------------

def function_starts(image):
    starts = {int(r["address"], 16) for r in csv.DictReader(open(os.path.join(ROOT, "build", "functions.csv")))}
    if image != "main":
        asm = os.path.join(ROOT, "build", "targets", image, "splat", "asm")
        for _, _, files in os.walk(asm):
            for f in files:
                m = re.match(r"func_([0-9A-F]{8})\.s$", f)
                if m:
                    starts.add(int(m.group(1), 16))
    return starts


def symbolize(asm, funcs):
    """$gp-relative and lui/addiu (lui/load-store) address pairs as %gp_rel/%hi/%lo of func_/D_ symbols."""
    def sym(a):
        if a in funcs:
            return f"func_{a:08X}"
        return f"D_{a:08X}" if 0x00100000 <= a < 0x02000000 else None

    lines = asm.split("\n")
    hi = {}
    out = list(lines)
    rx_lui = re.compile(r"lui\s+\$(\w+),\s*(0x[0-9A-Fa-f]+|\d+)\s*$")
    for i, l in enumerate(lines):
        body = l.split("*/")[-1].strip() if "*/" in l else l.strip()
        if body.startswith(".L") or not body:
            if body.endswith(":"):
                hi.clear()
            continue
        m = re.search(r"(-?0x[0-9A-Fa-f]+|-?\d+)\(\$gp\)", body)
        if m:
            s = sym((GP + int(m.group(1), 0)) & 0xFFFFFFFF)
            if s:
                out[i] = l.replace(m.group(0), f"%gp_rel({s})($gp)")
            continue
        m = rx_lui.search(body)
        if m:
            hi[m.group(1)] = (i, int(m.group(2), 0) << 16, None)
            continue
        m = re.search(r"^(addiu|daddiu)\s+\$(\w+),\s*\$(\w+),\s*(-?0x[0-9A-Fa-f]+|-?\d+)$", body)
        m2 = re.search(r"(-?0x[0-9A-Fa-f]+|-?\d+)\(\$(\w+)\)", body)
        reg = None
        if m and m.group(3) in hi:
            reg, imm, span = m.group(3), int(m.group(4), 0), m.group(4)
        elif m2 and m2.group(2) in hi:
            reg, imm, span = m2.group(2), int(m2.group(1), 0), m2.group(1) + "($" + m2.group(2) + ")"
        if reg is not None:
            li, base, s0 = hi[reg]
            a = (base + imm) & 0xFFFFFFFF
            s = sym(a)
            if s:
                if s0 is None:
                    out[li] = re.sub(r"(lui\s+\$\w+,\s*)(0x[0-9A-Fa-f]+|\d+)", lambda q: q.group(1) + f"%hi({s})", out[li])
                    hi[reg] = (li, base, a)
                    s0 = a
                ref = f"%lo({sym(s0)})" if a == s0 else f"%lo({sym(s0)}+{a - s0})"
                if m and m.group(3) == reg:
                    out[i] = l.replace(", " + span, ", " + ref) if (", " + span) in l else l
                else:
                    out[i] = l.replace(span, ref + "($" + reg + ")")
        m = re.search(r"^\w+\s+\$(\w+)", body)
        if m and m.group(1) in hi and not body.startswith(("sw", "sh", "sb", "sd", "sq", "swc1", "sdc1", "b", "j")):
            if hi[m.group(1)][0] != i:
                del hi[m.group(1)]
    return "\n".join(out)


def make_compilable(c, asm):
    """The earlier generator's post-processing: data not reached through $gp as char arrays, names."""
    import symbols
    gp = set(re.findall(r"%gp_rel\((D_[0-9A-F]{8})\)", asm))
    for m in list(re.finditer(r"^extern (.+?) (D_[0-9A-F]{8});$", c, re.M)):
        typ, name = m.group(1), m.group(2)
        if name in gp:
            continue
        c = re.sub(r"^extern .+? " + name + r";$", f"extern char {name}[];", c, flags=re.M)
        lines = c.splitlines()
        lines = [line if re.match(r"^(extern|typedef)\b", line) else
                 re.sub(r"(&?)\b" + name + r"\b", lambda q: f"((void *){name})" if q.group(1) else f"(*({typ} *){name})", line)
                 for line in lines]
        c = "\n".join(lines) + "\n"
    c = c.replace("? ", "M2C_UNK ").replace("?*", "M2C_UNK*")
    c = bitwise_casts(c)
    return symbols.rename_text(c)


def bitwise_casts(c):
    """M2C_BITWISE(type, expr) reinterprets the bits (a float register moved to an integer one); the
    shared header defines it as a value cast, which converts instead. Generated files get a real bit
    reinterpretation through a union (a GNU statement expression; ee-gcc and mwcc both accept it)."""
    out, i = [], 0
    key = "M2C_BITWISE("
    while True:
        j = c.find(key, i)
        if j < 0:
            out.append(c[i:])
            return "".join(out)
        out.append(c[i:j])
        k, depth = j + len(key), 1
        while depth and k < len(c):
            depth += {"(": 1, ")": -1}.get(c[k], 0)
            k += 1
        inner = c[j + len(key):k - 1]
        comma = 0
        depth = 0
        for n, ch in enumerate(inner):
            depth += {"(": 1, ")": -1}.get(ch, 0)
            if ch == "," and depth == 0:
                comma = n
                break
        typ, expr = inner[:comma].strip(), inner[comma + 1:].strip()
        src = "f32" if typ in ("s32", "u32", "s16", "u16", "s8", "u8", "M2C_UNK", "M2C_UNK32") else "s32"
        out.append(f"({{ union {{ {src} in_; {typ} out_; }} u_; u_.in_ = ({expr}); u_.out_; }})")
        i = k


# ---- one function -------------------------------------------------------------------------------

def generate(image, address, funcs, options=()):
    import match
    asm = symbolize(match.m2c_asm(address), funcs)
    d = os.path.join(OUT, image)
    os.makedirs(d, exist_ok=True)
    sfile = os.path.join(d, f"func_{address:08X}.s")
    open(sfile, "w").write(asm)
    try:
        run = subprocess.run([sys.executable, M2C, "-t", "mipsee-gcc-c", "--valid-syntax", *options, sfile],
                             capture_output=True, text=True, timeout=120)
    except subprocess.TimeoutExpired:
        return None, "m2c timed out"
    c = run.stdout
    if run.returncode or not c.strip():
        return None, "m2c failed: " + (run.stderr.strip().splitlines() or ["no output"])[-1][:120]
    bad = INCOMPLETE.search(c)
    if bad:
        return None, f"incomplete translation ({bad.group(0)})"
    return make_compilable(c, asm), None


def compiles(path):
    import match
    # a rejected translation's compiler errors are noise in a batch log: send them to /dev/null
    saved = os.dup(1), os.dup(2)
    null = os.open(os.devnull, os.O_WRONLY)
    os.dup2(null, 1)
    os.dup2(null, 2)
    try:
        obj = match.compile_c(path)
    except SystemExit:
        return None
    finally:
        os.dup2(saved[0], 1)
        os.dup2(saved[1], 2)
        for fd in (*saved, null):
            os.close(fd)
    if obj and os.path.exists(obj):
        return obj
    return None


# m2c settings tried in order when a translation does not compile: plainer control flow each time
M2C_LADDER = ((), ("--no-switches",), ("--no-switches", "--no-andor"), ("--gotos-only",))
GCC_TYPES = "typedef int s128 __attribute__((mode(TI)));\ntypedef unsigned int u128 __attribute__((mode(TI)));\n\n"


def variants(body):
    """The translation, then with m2c's untyped `void *` as `char *` (m2c means byte offsets)."""
    yield "as is", body
    if "void *" in body:
        yield "char pointers", re.sub(r"\bvoid \*", "char *", body)


def one(image, address, symbol, funcs, base, cache):
    import equiv
    path = os.path.join(OUT, image, f"func_{address:08X}.c")
    obj = comp = tried = None
    first_why = None
    for options in M2C_LADDER:
        body, why = generate(image, address, funcs, options)
        if body is None:
            first_why = first_why or why
            continue
        for label, text in variants(body):
            # -G0 first: constants then live in .rodata (absolute), not in a $gp literal pool
            for comp in ("ee-gcc-2.9-G0", "ee-gcc-2.9", "mwcc-3.0.1b210"):
                extra = GCC_TYPES if comp.startswith("ee-gcc") and "128" in text else ""
                open(path, "w").write(HEADER.format(comp=comp) + extra + text)
                obj = compiles(path)
                if obj:
                    tried = " ".join(options) or "default"
                    tried += "" if label == "as is" else f", {label}"
                    break
            if obj:
                break
        if obj:
            break
    if obj is None:
        if first_why and not os.path.exists(path):
            return {"verdict": "NO-C", "detail": first_why}
        return {"verdict": "NO-COMPILE", "detail": "no m2c setting gives C either compiler accepts", "source": path}
    try:
        res = equiv.judge(image, address, path, symbol, base, obj, cache)
    finally:
        try:
            os.remove(obj)
        except OSError:
            pass
    res.update({"source": os.path.relpath(path, ROOT), "compiler": comp, "m2c": tried})
    return res


def _worker(args):
    image, rows = args
    import signal
    import equiv
    import symbols
    funcs = function_starts(image)
    base = equiv.build_memory(image)
    cache = {}
    out = []
    for address in rows:
        def _timeout(sig, frm):
            raise TimeoutError()
        signal.signal(signal.SIGALRM, _timeout)
        signal.alarm(equiv.FUNCTION_TIMEOUT)
        try:
            res = one(image, address, symbols.symbol(address), funcs, base, cache)
        except TimeoutError:
            res = {"verdict": "UNTESTABLE", "detail": f"timeout ({equiv.FUNCTION_TIMEOUT} s)"}
        except Exception as e:                       # one function must not stop the batch
            res = {"verdict": "ERROR", "detail": f"{type(e).__name__}: {e}"}
        finally:
            signal.alarm(0)
        res["address"] = f"{address:08X}"
        res.pop("key", None)
        with open(os.path.join(OUT, f"{image}.jsonl"), "a") as fh:
            fh.write(json.dumps(res) + "\n")
        print(f"{image} {address:08X} {res['verdict']} {res.get('detail', '')}"
              + (f" cases={res.get('cases')}+{res.get('holdout')} coverage={res.get('coverage')}%" if res["verdict"] == "EQUIVALENT" else ""),
              flush=True)
        out.append(res)
    return out


def has_c(image):
    """Addresses of the image that already have C: exact sources and non-matching drafts."""
    env = {k: v for k, v in os.environ.items() if k != "PES6_TARGET"}
    if image != "main":
        env["PES6_TARGET"] = image
    code = "import sys,json; sys.path.insert(0,'tools'); import project; print(json.dumps(sorted(project.sources())))"
    r = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, env=env, check=True)
    exact = set(json.loads(r.stdout.strip().splitlines()[-1]))
    man = json.load(open(os.path.join(ROOT, "config", "nonmatching.json")))
    drafts = {int(x["address"], 16) for x in man["functions"] if x["image"] == image}
    return exact | drafts


def run(list_path, jobs, limit, only_image):
    import multiprocessing
    Pool = multiprocessing.get_context("fork").Pool
    os.makedirs(OUT, exist_ok=True)
    rows = {}
    for r in csv.DictReader(open(list_path)):
        if only_image and r["image"] != only_image:
            continue
        if r.get("status") in ("boundary",):             # library code the port replaces
            continue
        rows.setdefault(r["image"], []).append(int(r["address"], 16))
    for image, addrs in rows.items():
        done = set()
        p = os.path.join(OUT, f"{image}.jsonl")
        if os.path.exists(p):
            for line in open(p):
                try:
                    done.add(int(json.loads(line)["address"], 16))
                except (ValueError, KeyError):
                    pass
        covered = has_c(image)
        todo = [a for a in addrs if a not in covered and a not in done]
        if limit:
            todo = todo[:limit]
        print(f"{image}: {len(addrs)} listed, {len(addrs) - len([a for a in addrs if a not in covered])} have C, "
              f"{len(done)} already generated, {len(todo)} to go", flush=True)
        if image == "main":
            os.environ.pop("PES6_TARGET", None)
        else:
            os.environ["PES6_TARGET"] = image
        chunks = [(image, todo[i:i + 10]) for i in range(0, len(todo), 10)]
        counts = {}
        with Pool(jobs) as pool:
            for out in pool.imap_unordered(_worker, chunks):
                for r in out:
                    counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
        print(f"{image}: {counts}", flush=True)


REVIEW = ("Generated by tools/gen_equiv.py from m2c and admitted because tools/equiv.py found it equivalent to the "
          "original on generated cases (see docs/equivalent.md for cases and coverage); compiler/structural checks "
          "as for every draft. Behavioural evidence on test cases, not a semantic-equivalence proof.")
KNOWN = ["Compiled instruction layout differs from the original.",
         "Types, local layouts, and call contracts remain provisional; equivalence holds only on the generated cases."]


def admit(only_image):
    """Copy every EQUIVALENT generated file into nonmatching/<image>/, keep those tools/nonmatching.py's own
    verification accepts, and record them in config/nonmatching.json and the equivalence results."""
    import shutil
    man_path = os.path.join(ROOT, "config", "nonmatching.json")
    for fn in sorted(os.listdir(OUT)):
        m = re.match(r"(\w+)\.jsonl$", fn)
        if not m or (only_image and m.group(1) != only_image):
            continue
        image = m.group(1)
        results = {}
        for line in open(os.path.join(OUT, fn)):
            r = json.loads(line)
            results[r["address"]] = r
        covered = has_c(image)
        rows, copied = [], {}
        env = {k: v for k, v in os.environ.items() if k != "PES6_TARGET"}
        if image != "main":
            env["PES6_TARGET"] = image
        names = subprocess.run([sys.executable, "-c",
                                "import sys,json; sys.path.insert(0,'tools'); import layout; "
                                "print(json.dumps({a: layout.stem(int(a,16)) for a in json.load(sys.stdin)}))"],
                               input=json.dumps([a for a, r in results.items() if r["verdict"] == "EQUIVALENT"]),
                               capture_output=True, text=True, env=env, check=True)
        stems = json.loads(names.stdout.strip().splitlines()[-1])
        sym = subprocess.run([sys.executable, "-c",
                              "import sys,json; sys.path.insert(0,'tools'); import symbols; "
                              "print(json.dumps({a: symbols.symbol(int(a,16)) for a in json.load(sys.stdin)}))"],
                             input=json.dumps(list(stems)), capture_output=True, text=True, env=env, check=True)
        symbol_of = json.loads(sym.stdout.strip().splitlines()[-1])
        for a, r in sorted(results.items()):
            if r["verdict"] != "EQUIVALENT" or int(a, 16) in covered:
                continue
            dest = os.path.join("nonmatching", image, stems[a] + ".c")
            os.makedirs(os.path.dirname(os.path.join(ROOT, dest)), exist_ok=True)
            shutil.copy(os.path.join(ROOT, r["source"]), os.path.join(ROOT, dest))
            copied[a] = dest
            rows.append({"image": image, "address": a, "symbol": symbol_of[a], "source": dest, "compiler": r["compiler"],
                         "minimum_similarity": 0, "review": REVIEW, "known_issues": KNOWN})
        if not rows:
            print(f"{image}: nothing to admit")
            continue
        code = ("import json,sys; sys.path.insert(0,'tools'); import nonmatching; "
                "rows=json.load(sys.stdin); print(json.dumps(nonmatching.inspect(rows, jobs=4)))")
        r = subprocess.run([sys.executable, "-c", code], input=json.dumps(rows), capture_output=True, text=True, env=env)
        try:
            checked = json.loads(r.stdout.strip().splitlines()[-1])
        except (ValueError, IndexError):
            sys.exit(f"{image}: verification failed to run: {r.stderr[-400:]}")
        man = json.load(open(man_path))
        good, bad = 0, {}
        eq_path = os.path.join(ROOT, "build", "equiv", f"partial-{image}.jsonl")
        os.makedirs(os.path.dirname(eq_path), exist_ok=True)
        for x in checked:
            if x.get("verified"):
                man["functions"].append({k: x[k] for k in ("image", "address", "symbol", "source", "compiler", "source_sha256",
                                                          "original_sha256", "minimum_similarity", "review", "known_issues")})
                res = dict(results[x["address"]], symbol=x["symbol"], source=x["source"])
                with open(eq_path, "a") as fh:
                    fh.write(json.dumps(res) + "\n")
                good += 1
            else:
                os.remove(os.path.join(ROOT, copied[x["address"]]))
                reason = re.sub(r"[0-9A-F]{8}|0x[0-9a-f]+", "#", x.get("error", "?"))[:80]
                bad[reason] = bad.get(reason, 0) + 1
        json.dump(man, open(man_path, "w"), indent=1)
        open(man_path, "a").write("\n")
        print(f"{image}: admitted {good}; not admitted {sum(bad.values())}: {bad}")


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    jobs = int(a[a.index("--jobs") + 1]) if "--jobs" in a else 2
    limit = int(a[a.index("--limit") + 1]) if "--limit" in a else 0
    image = a[a.index("--image") + 1] if "--image" in a else None
    if a[0] == "--admit":
        return admit(image)
    run(a[0], jobs, limit, image)


if __name__ == "__main__":
    main()
